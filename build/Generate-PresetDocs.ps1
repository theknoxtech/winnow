#Requires -Version 5.1
<#
.SYNOPSIS
    Regenerates the preset reference tables in README.md from DefaultPresets.json.

.DESCRIPTION
    The preset reference in the README used to be maintained by hand, which meant it could drift
    from the presets the app actually shipped - and did. This regenerates the section between the
    PRESET-REFERENCE markers so the documentation cannot disagree with the code.

.PARAMETER Check
    Verify the README is up to date without modifying it. Exits non-zero if it is stale, so CI
    can enforce it.

.EXAMPLE
    .\build\Generate-PresetDocs.ps1
    .\build\Generate-PresetDocs.ps1 -Check
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'

$repoRoot   = Split-Path $PSScriptRoot -Parent
$presetFile = Join-Path $repoRoot 'src\Winnow.Core\Presets\DefaultPresets.json'
$readme     = Join-Path $repoRoot 'README.md'

$startMarker = '<!-- PRESET-REFERENCE:START - generated by build\Generate-PresetDocs.ps1, do not edit by hand -->'
$endMarker   = '<!-- PRESET-REFERENCE:END -->'

$doc = Get-Content $presetFile -Raw | ConvertFrom-Json

function Escape-Cell([string]$text) {
    if (-not $text) { return '' }
    # A pipe inside a cell would break the table.
    $text.Replace('|', '\|').Trim()
}

$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine($startMarker)
$null = $sb.AppendLine()

foreach ($group in ($doc.presets | Group-Object group)) {
    $null = $sb.AppendLine("### $($group.Name)")
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('| Preset | Log(s) | Event ID(s) | What it shows | Scoped by |')
    $null = $sb.AppendLine('|---|---|---|---|---|')

    foreach ($preset in $group.Group) {
        $logs = ($preset.clauses | ForEach-Object { $_.logName }) -join '<br>'

        $ids = ($preset.clauses | ForEach-Object {
            if ($_.eventIds -and $_.eventIds.Count -gt 0) { $_.eventIds -join ', ' } else { '_all_' }
        }) -join '<br>'

        $scope = @()
        $providers = $preset.clauses | Where-Object { $_.providerNames } |
                     ForEach-Object { $_.providerNames } | Select-Object -Unique
        if ($providers) { $scope += 'provider ' + (($providers | ForEach-Object { "``$_``" }) -join ', ') }
        if ($preset.messageFilter) { $scope += "message contains ""$($preset.messageFilter)""" }

        $cells = @(
            (Escape-Cell $preset.label)
            (Escape-Cell $logs)
            (Escape-Cell $ids)
            (Escape-Cell $preset.description)
            (Escape-Cell ($scope -join '; '))
        )
        $null = $sb.AppendLine('| ' + ($cells -join ' | ') + ' |')
    }
    $null = $sb.AppendLine()
}

$null = $sb.Append($endMarker)
$generated = $sb.ToString().TrimEnd()

$content = Get-Content $readme -Raw
$startIndex = $content.IndexOf($startMarker)
$endIndex   = $content.IndexOf($endMarker)

if ($startIndex -lt 0 -or $endIndex -lt 0) {
    throw "Could not find the PRESET-REFERENCE markers in README.md."
}

$before = $content.Substring(0, $startIndex)
$after  = $content.Substring($endIndex + $endMarker.Length)
$updated = $before + $generated + $after

# Compare and write with one line ending throughout.
#
# Without this the check is not stable: PowerShell's output here is CRLF, an editor writing the
# surrounding prose may use LF, and the file ends up mixed - so -Check reports "out of date" for a
# section whose content is byte-identical, failing CI for no real reason. Git already normalises
# these files to LF on commit (see .gitattributes), so LF is the canonical form to compare in.
function ConvertTo-Lf([string]$text) {
    if ($null -eq $text) { return '' }
    $text -replace "`r`n", "`n"
}

if ($Check) {
    if ((ConvertTo-Lf $content) -ne (ConvertTo-Lf $updated)) {
        Write-Error "README.md preset reference is out of date. Run: .\build\Generate-PresetDocs.ps1"
        exit 1
    }
    Write-Host "README.md preset reference is up to date ($($doc.presets.Count) presets)." -ForegroundColor Green
    exit 0
}

# Written as LF so the file stays internally consistent regardless of what last edited it.
$normalised = ConvertTo-Lf $updated
[System.IO.File]::WriteAllText($readme, $normalised, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Regenerated the preset reference for $($doc.presets.Count) presets." -ForegroundColor Green
