#Requires -Version 5.1
<#
.SYNOPSIS
    Regenerates the preset reference tables in README.md from Winnow.ps1.

.DESCRIPTION
    The preset reference in the README used to be maintained by hand, which meant it could drift
    from the presets the app actually shipped - and did. This regenerates the section between the
    PRESET-REFERENCE markers so the documentation cannot disagree with the code.

    Presets are read out of Winnow.ps1 itself, which is the shipped artifact and therefore the
    single source of truth. Rather than parse the file with regular expressions, this locates the
    $script:Presets assignment through PowerShell's own parser and evaluates just that expression.
    The right-hand side is a pure array literal of ordered hashtables - data with no side effects -
    so evaluating it in isolation is safe, and it means the table can never disagree with what the
    script will actually load at run time.

.PARAMETER Check
    Verify the README is up to date without modifying it. Exits non-zero if it is stale, so CI
    can enforce it.

.EXAMPLE
    .\build\Generate-PresetDocs.ps1
    .\build\Generate-PresetDocs.ps1 -Check
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'

$repoRoot   = Split-Path $PSScriptRoot -Parent
$scriptFile = Join-Path $repoRoot 'Winnow.ps1'
$readme     = Join-Path $repoRoot 'README.md'

$startMarker = '<!-- PRESET-REFERENCE:START - generated by build\Generate-PresetDocs.ps1, do not edit by hand -->'
$endMarker   = '<!-- PRESET-REFERENCE:END -->'

# --- Read the presets straight out of the shipped script --------------------
$ast = [System.Management.Automation.Language.Parser]::ParseFile($scriptFile, [ref]$null, [ref]$null)

$assignment = $ast.FindAll({
    param($node)
    $node -is [System.Management.Automation.Language.AssignmentStatementAst] -and
    $node.Left.Extent.Text -eq '$script:Presets'
}, $true) | Select-Object -First 1

if (-not $assignment) {
    throw "Could not find the `$script:Presets assignment in $scriptFile."
}

$presets = Invoke-Expression $assignment.Right.Extent.Text
if (-not $presets -or $presets.Count -eq 0) {
    throw "The `$script:Presets assignment in $scriptFile evaluated to nothing."
}

function Escape-Cell([string]$text) {
    if (-not $text) { return '' }
    # A pipe inside a cell would break the table.
    $text.Replace('|', '\|').Trim()
}

# The presets use .Contains() guards throughout the app because the script runs under
# Set-StrictMode, where reading an absent key throws rather than returning $null. Same here.
function Get-Field($preset, [string]$name) {
    if ($preset.Contains($name)) { return $preset[$name] }
    return $null
}

$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine($startMarker)
$null = $sb.AppendLine()

foreach ($group in ($presets | Group-Object { $_.Group })) {
    $null = $sb.AppendLine("### $($group.Name)")
    $null = $sb.AppendLine()
    $null = $sb.AppendLine('| Preset | Log(s) | Event ID(s) | What it shows | Scoped by |')
    $null = $sb.AppendLine('|---|---|---|---|---|')

    foreach ($preset in $group.Group) {
        # A preset can span a second log, which the script expresses as LogName2/Id2.
        $logs = @(Get-Field $preset 'LogName')
        $ids  = @()

        $primaryIds = Get-Field $preset 'Id'
        $ids += if ($primaryIds) { $primaryIds -join ', ' } else { '_all_' }

        $secondLog = Get-Field $preset 'LogName2'
        if ($secondLog) {
            $logs += $secondLog
            $secondIds = Get-Field $preset 'Id2'
            $ids += if ($secondIds) { $secondIds -join ', ' } else { '_all_' }
        }

        $scope     = @()
        $providers = Get-Field $preset 'ProviderName'
        if ($providers) {
            $scope += 'provider ' + (($providers | ForEach-Object { "``$_``" }) -join ', ')
        }
        $messageFilter = Get-Field $preset 'MessageFilter'
        if ($messageFilter) { $scope += "message contains ""$messageFilter""" }

        $cells = @(
            (Escape-Cell (Get-Field $preset 'Label'))
            (Escape-Cell ($logs -join '<br>'))
            (Escape-Cell ($ids  -join '<br>'))
            (Escape-Cell (Get-Field $preset 'Description'))
            (Escape-Cell ($scope -join '; '))
        )
        $null = $sb.AppendLine('| ' + ($cells -join ' | ') + ' |')
    }
    $null = $sb.AppendLine()
}

$null = $sb.Append($endMarker)
$generated = $sb.ToString().TrimEnd()

$content = Get-Content $readme -Raw
$startIndex = $content.IndexOf($startMarker)
$endIndex   = $content.IndexOf($endMarker)

if ($startIndex -lt 0 -or $endIndex -lt 0) {
    throw "Could not find the PRESET-REFERENCE markers in README.md."
}

$before = $content.Substring(0, $startIndex)
$after  = $content.Substring($endIndex + $endMarker.Length)
$updated = $before + $generated + $after

# Compare and write with one line ending throughout.
#
# Without this the check is not stable: PowerShell's output here is CRLF, an editor writing the
# surrounding prose may use LF, and the file ends up mixed - so -Check reports "out of date" for a
# section whose content is byte-identical, failing CI for no real reason. Git already normalises
# these files to LF on commit (see .gitattributes), so LF is the canonical form to compare in.
function ConvertTo-Lf([string]$text) {
    if ($null -eq $text) { return '' }
    $text -replace "`r`n", "`n"
}

if ($Check) {
    if ((ConvertTo-Lf $content) -ne (ConvertTo-Lf $updated)) {
        Write-Error "README.md preset reference is out of date. Run: .\build\Generate-PresetDocs.ps1"
        exit 1
    }
    Write-Host "README.md preset reference is up to date ($($presets.Count) presets)." -ForegroundColor Green
    exit 0
}

# Written as LF so the file stays internally consistent regardless of what last edited it.
$normalised = ConvertTo-Lf $updated
[System.IO.File]::WriteAllText($readme, $normalised, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Regenerated the preset reference for $($presets.Count) presets." -ForegroundColor Green
